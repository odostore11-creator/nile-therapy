let LANG = 'ar'; // Arabic first; English only if this device chose it
try { if (localStorage.getItem('nt_lang') === 'en') LANG = 'en'; } catch { /* storage blocked: stay Arabic */ }

function t(key, vars) {
  let s = STRINGS[LANG][key] ?? STRINGS.en[key] ?? key;
  if (typeof s === 'function') return s(vars);
  if (vars && typeof s === 'string') s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m));
  return s;
}
function trServer(msg) { return LANG === 'ar' ? (SERVER_MESSAGES_AR[msg] ?? msg) : msg; }

function applyLang() {
  document.documentElement.lang = LANG;
  document.documentElement.dir = LANG === 'ar' ? 'rtl' : 'ltr';
  document.title = t('app.title');
}
function setLang(next) {
  LANG = next === 'ar' ? 'ar' : 'en';
  try { localStorage.setItem('nt_lang', LANG); } catch { /* not saved; still switches for this visit */ }
  applyLang();
}
